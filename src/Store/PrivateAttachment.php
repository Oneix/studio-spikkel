<?php
declare(strict_types=1);

namespace App\Store;

use finfo;
use InvalidArgumentException;
use Psr\Http\Message\UploadedFileInterface;
use RuntimeException;

final class PrivateAttachment
{
    private const MAX_BYTES = 5 * 1024 * 1024;
    private const EXTENSIONS = [
        'image/jpeg' => ['jpg', 'jpeg'],
        'image/png' => ['png'],
        'application/pdf' => ['pdf'],
    ];

    /**
     * Keep attachments outside the document root.
     */
    public function __construct(private readonly string $directory)
    {
    }

    /**
     * Use the same storage location when saving and downloading maker attachments.
     */
    public static function forCollaborations(): self
    {
        return new self(ROOT . DS . 'storage' . DS . 'uploads' . DS . 'collaborations');
    }

    /**
     * Resolve a stored key to a readable regular file in the private directory.
     */
    public function availablePath(string $key): ?string
    {
        try {
            $path = $this->path($key);
        } catch (InvalidArgumentException) {
            return null;
        }
        $resolved = realpath($path);
        if ($resolved === false || dirname($resolved) !== realpath($this->directory)) {
            return null;
        }

        return !is_link($path) && is_file($resolved) && is_readable($resolved) ? $resolved : null;
    }

    /**
     * Check the uploaded bytes rather than relying on the type reported by the browser.
     *
     * @return array{attachment_key: string, attachment_name: string, attachment_type: string, attachment_size: int}
     */
    public function inspect(UploadedFileInterface $file): array
    {
        $error = $file->getError();
        $size = $file->getSize();
        if (in_array($error, [UPLOAD_ERR_INI_SIZE, UPLOAD_ERR_FORM_SIZE], true) || $size > self::MAX_BYTES) {
            throw new InvalidArgumentException('Kies een bestand van maximaal 5 MB.');
        }
        if ($error !== UPLOAD_ERR_OK || $size === null || $size < 1) {
            throw new InvalidArgumentException('De bijlage kon niet worden gelezen. Kies het bestand opnieuw.');
        }

        $stream = $file->getStream();
        $stream->rewind();
        $bytes = $stream->read(self::MAX_BYTES + 1);
        $stream->rewind();
        $mime = (new finfo(FILEINFO_MIME_TYPE))->buffer($bytes);
        $name = basename(str_replace('\\', '/', $file->getClientFilename() ?? ''));
        $name = preg_replace('/[\x00-\x1f\x7f]/', '', $name) ?? '';
        $extension = strtolower(pathinfo($name, PATHINFO_EXTENSION));
        if (strlen($bytes) !== $size || !in_array($extension, self::EXTENSIONS[$mime] ?? [], true)) {
            throw new InvalidArgumentException('Voeg een geldige JPG, PNG of PDF toe.');
        }
        if ($mime === 'application/pdf') {
            $contentsMatch = str_starts_with($bytes, '%PDF-');
        } else {
            // phpcs:ignore Generic.PHP.NoSilencedErrors.Discouraged -- Invalid input gets a field error instead.
            $image = @getimagesizefromstring($bytes);
            $contentsMatch = ($image['mime'] ?? null) === $mime;
        }
        if (!$contentsMatch) {
            throw new InvalidArgumentException('Voeg een geldige JPG, PNG of PDF toe.');
        }

        return [
            'attachment_key' => bin2hex(random_bytes(16)) . '.' . self::EXTENSIONS[$mime][0],
            'attachment_name' => mb_substr($name, 0, 160),
            'attachment_type' => $mime,
            'attachment_size' => $size,
        ];
    }

    /**
     * Move a verified upload to the private location under its server-generated key.
     */
    public function store(UploadedFileInterface $file, string $key): void
    {
        // phpcs:ignore Generic.PHP.NoSilencedErrors.Discouraged -- Another request may create it first.
        if (!is_dir($this->directory) && !@mkdir($this->directory, 0700, true) && !is_dir($this->directory)) {
            throw new RuntimeException('Could not create the private attachment directory.');
        }
        $file->moveTo($this->path($key));
    }

    /**
     * Clean up an attachment if the database transaction could not finish.
     */
    public function discard(string $key): void
    {
        $path = $this->path($key);
        if (is_file($path) && !unlink($path)) {
            throw new RuntimeException('Could not remove an unlinked attachment.');
        }
    }

    /**
     * Accept only keys generated by this service.
     */
    private function path(string $key): string
    {
        if (!preg_match('/\A[0-9a-f]{32}\.(?:jpg|png|pdf)\z/', $key)) {
            throw new InvalidArgumentException('Invalid private attachment key.');
        }

        return $this->directory . DIRECTORY_SEPARATOR . $key;
    }
}
